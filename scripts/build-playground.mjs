// Combines every .c4 file in the project into one file that can be pasted into
// the LikeC4 playground (https://playground.likec4.dev). LikeC4 merges top-level
// blocks, so the files are concatenated as-is, specification first.
//
// Usage: node scripts/build-playground.mjs   ->   dist/food-delivery-playground.c4
//
// Not carried over: settings in likec4.config.json (relationship browser
// scope), and relative `link`s to ADRs and backlog files, which won't resolve
// in the playground.

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, relative, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = join(root, 'dist', 'food-delivery-playground.c4')

const c4Files = dir =>
  readdirSync(join(root, dir))
    .filter(name => name.endsWith('.c4'))
    .sort()
    .map(name => join(root, dir, name))

const order = [
  join(root, 'model', 'specification.c4'),
  join(root, 'model', 'styles.c4'),
  join(root, 'model', 'actorGroups.c4'),
  join(root, 'model', 'powerAndMoney.c4'),
  join(root, 'model', 'capabilities.c4'),
  join(root, 'model', 'standards.c4'),
  ...c4Files(join('model', 'systems')),
  join(root, 'model', 'deployment.c4'),
  join(root, 'views', 'map.c4'),
  ...c4Files('views').filter(file => !file.endsWith('map.c4'))
]

// Fail loudly if a .c4 file exists that the order above doesn't cover
const all = [...c4Files('model'), ...c4Files(join('model', 'systems')), ...c4Files('views')]
const missing = all.filter(file => !order.includes(file))
if (missing.length) {
  console.error('Not included in build order:\n  ' + missing.map(f => relative(root, f)).join('\n  '))
  process.exit(1)
}

const banner = `// Food Delivery Reference Architecture, combined for the LikeC4 playground.
// Generated by scripts/build-playground.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit:
// change the source files and regenerate.
`

const body = order
  .map(file => `\n// ==== ${relative(root, file).replaceAll('\\', '/')} ====\n\n${readFileSync(file, 'utf8').trim()}\n`)
  .join('')

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, banner + body)
console.log(`Wrote ${relative(root, outFile)} (${order.length} files)`)
